"""Record the baltic summary of each tree file as its expected values.

Writes ``trees/<program>/expected.yaml``, which ``tests/test_tree_files.py``
compares against. Review the diff before committing: the snapshot is taken with
whichever baltic is installed, so a parsing bug would be recorded as correct.

    python tools/snapshot.py                    # every tree
    python tools/snapshot.py beast2 iqtree/     # some programs
    python tools/snapshot.py beast1/miniFluB    # files whose id contains this
"""

import argparse
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "tests"))

import baltic as bt  # noqa: E402
from treefiles import EXPECTED_FILE, discover, load, read_expected, summarize  # noqa: E402


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("filters", nargs="*", help="only snapshot trees whose id (program/file) contains one of these")
    args = parser.parse_args()

    cases = [c for c in discover() if not args.filters or any(f in c.id for f in args.filters)]
    if not cases:
        sys.exit("No trees match.")

    print(f"Snapshotting with baltic from {Path(bt.__file__).parent}")
    by_dir = {}
    for case in cases:
        print(f"  {case.id}")
        by_dir.setdefault(case.path.parent, {})[case.path.name] = summarize(load(case))

    for directory, summaries in by_dir.items():
        expected = read_expected(directory)
        expected.update(summaries)
        names = [c.path.name for c in discover() if c.path.parent == directory]
        expected = {name: expected[name] for name in names if name in expected}
        text = "# Generated by tools/snapshot.py; review diffs before committing.\n"
        text += yaml.safe_dump(expected, sort_keys=False)
        (directory / EXPECTED_FILE).write_text(text, encoding="utf-8")
        print(f"Wrote {directory / EXPECTED_FILE}")


if __name__ == "__main__":
    main()
